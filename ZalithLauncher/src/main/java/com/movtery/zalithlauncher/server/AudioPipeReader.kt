package com.movtery.zalithlauncher.server

import android.util.Log
import com.movtery.zalithlauncher.path.PathManager
import java.io.File
import java.io.FileOutputStream
import java.io.IOException
import java.io.RandomAccessFile
import java.util.concurrent.atomic.AtomicBoolean

private const val TAG = "AudioPipe"

/** 音频管道参数，必须与 alsoft.conf 里写的一致 */
object AudioPipeSpec {
    const val SAMPLE_RATE = 48000
    const val CHANNEL_COUNT = 2
    const val BITS_PER_SAMPLE = 16
    const val FRAME_BYTES = CHANNEL_COUNT * (BITS_PER_SAMPLE / 8)
}

/**
 * 游戏声音管道。
 *
 * 原理：把 OpenAL Soft 的音频后端从 `opensl` 换成 `wave`，
 * 让它把混音结果写进我们指定的文件（`alsoft.conf` 的 `[wave] file=`），
 * 于是游戏声音不再走扬声器，而是变成裸 PCM 流。这里把这条流读出来
 * 交给 AAC 编码器，最终推给客户端。
 *
 * 这样做的好处：
 *  - 宿主设备完全静音（服务器不该自己发声）
 *  - 不依赖 Android 10 的 AudioPlaybackCapture，也不需要录屏/录音权限
 *  - 安卓 8 及以上都能用
 *
 * 关于 FIFO：
 * `wave.cpp` 用普通 `std::ostream` 打开文件，启动/结束时会 `seekp` 回填
 * WAV 头，这些 seek 在 FIFO 上会静默失败——正好，我们拿到的就是**裸 PCM**，
 * 不需要解析 WAV 头。但 FIFO 依赖 `mkfifo` 命令，部分 ROM 上没有，
 * 因此保留普通文件的降级路径。
 */
class AudioPipeReader(
    private val onPcm: (ByteArray, Int) -> Unit,
    private val onFailure: (Throwable) -> Unit = {}
) {
    /** 管道/文件路径 */
    val pipeFile: File = File(PathManager.DIR_CACHE, "stream_audio.pcm")

    /** 配套的 alsoft 配置文件 */
    val configFile: File = File(PathManager.DIR_CACHE, "alsoft.conf")

    private val running = AtomicBoolean(false)
    private var readThread: Thread? = null

    /** FIFO 还是普通文件 */
    @Volatile
    private var isFifo = false

    /** 普通文件模式下已读到的位置 */
    private var readOffset = 0L

    /**
     * 生成 alsoft.conf 并创建管道
     * @return 是否成功（失败时调用方应回退到其它音频来源）
     */
    fun prepare(): Boolean {
        return runCatching {
            pipeFile.parentFile?.mkdirs()
            //上一次残留的普通文件会让 OpenAL 以为可以直接写，清掉重来
            if (pipeFile.exists() && !pipeFile.isDirectory) pipeFile.delete()

            isFifo = createFifo(pipeFile)
            if (!isFifo) {
                //建不了 FIFO 就退化成普通文件：OpenAL 正常写，我们轮询增量读取
                if (!pipeFile.createNewFile()) {
                    throw IOException("Cannot create audio sink at ${pipeFile.absolutePath}")
                }
            }
            writeConfig()
            Log.i(TAG, "Audio sink ready (fifo=$isFifo): ${pipeFile.absolutePath}")
            true
        }.onFailure {
            Log.w(TAG, "Failed to prepare the audio pipe", it)
            onFailure(it)
        }.getOrDefault(false)
    }

    /**
     * 写 alsoft.conf。
     *
     * 采样参数在这里固定下来，服务端就不用去猜 PCM 格式了。
     * `seekp` 在 FIFO 上会失败，但不影响数据写入，因此 header 里
     * 的长度字段会保持占位值——我们按裸 PCM 处理即可。
     */
    private fun writeConfig() {
        val text = buildString {
            appendLine("# Generated by Zalith Launcher 2 streaming server")
            appendLine("[general]")
            appendLine("channels = stereo")
            appendLine("frequency = ${AudioPipeSpec.SAMPLE_RATE}")
            appendLine("sample-type = short")
            appendLine("drivers = wave")
            appendLine()
            appendLine("[wave]")
            appendLine("file = ${pipeFile.absolutePath}")
            appendLine("format = wav")
        }
        FileOutputStream(configFile, false).use { out ->
            out.write(text.toByteArray(Charsets.UTF_8))
            out.flush()
        }
    }

    /**
     * 建 FIFO。Android 的 `android.system.Os` 没有 mkfifo，
     * 这里直接调 toybox 的 mkfifo，失败则返回 false 走普通文件。
     */
    private fun createFifo(file: File): Boolean {
        return runCatching {
            val process = ProcessBuilder("mkfifo", "-m", "600", file.absolutePath)
                .redirectErrorStream(true)
                .start()
            val output = process.inputStream.bufferedReader().readText()
            val code = process.waitFor()
            if (code != 0) {
                Log.w(TAG, "mkfifo exited $code: $output")
                return false
            }
            file.exists()
        }.getOrElse {
            Log.w(TAG, "mkfifo unavailable", it)
            false
        }
    }

    /**
     * 开始读取。会阻塞在 open 上直到 OpenAL 真正打开写端。
     */
    fun start(): Boolean {
        if (running.get()) return true
        if (!pipeFile.exists()) {
            if (!prepare()) return false
        }
        running.set(true)
        readThread = Thread({ readLoop() }, "ZalithAudioPipe").apply {
            isDaemon = true
            start()
        }
        return true
    }

    private fun readLoop() {
        val buffer = ByteArray(16 * 1024)
        var emptyReads = 0
        while (running.get()) {
            try {
                if (isFifo) {
                    //阻塞式打开：OpenAL 打开写端之后才会返回
                    java.io.FileInputStream(pipeFile).use { stream ->
                        while (running.get()) {
                            val read = stream.read(buffer)
                            if (read < 0) break
                            if (read == 0) continue
                            emptyReads = 0
                            deliver(buffer, read)
                        }
                    }
                } else {
                    val read = readGrowingFile(buffer)
                    if (read <= 0) {
                        //普通文件没有新数据，稍等再看
                        if (++emptyReads > 20) {
                            Thread.sleep(20)
                        }
                        continue
                    }
                    emptyReads = 0
                    deliver(buffer, read)
                }
            } catch (_: InterruptedException) {
                return
            } catch (e: Throwable) {
                if (!running.get()) return
                Log.w(TAG, "Audio pipe read error, retrying", e)
                onFailure(e)
                runCatching { Thread.sleep(500) }
            }
        }
    }

    /**
     * 把读到的字节对齐到完整帧后回调
     */
    private fun deliver(buffer: ByteArray, length: Int) {
        val aligned = length - (length % AudioPipeSpec.FRAME_BYTES)
        if (aligned <= 0) return
        onPcm(buffer.copyOf(aligned), aligned)
    }

    /**
     * 普通文件降级路径：按已读位置增量读取
     */
    private fun readGrowingFile(buffer: ByteArray): Int {
        return runCatching {
            RandomAccessFile(pipeFile, "r").use { file ->
                val size = file.length()
                if (size <= readOffset) return 0
                //文件被 OpenAL 重写过（重启）就从头再来
                if (size < readOffset) readOffset = 0L
                file.seek(readOffset)
                val available = (size - readOffset).coerceAtMost(buffer.size.toLong()).toInt()
                val read = file.read(buffer, 0, available)
                if (read > 0) readOffset += read
                read
            }
        }.getOrElse {
            Log.w(TAG, "Growing-file read failed", it)
            0
        }
    }

    fun stop() {
        running.set(false)
        readThread?.interrupt()
        readThread = null
        readOffset = 0L
    }

    /**
     * 清理产物
     */
    fun cleanup() {
        stop()
        runCatching { if (pipeFile.exists()) pipeFile.delete() }
    }
}
